for (const width of [320, 375, 390, 430, 768, 1024, 1280, 1440, 1920]) {
  test(`Admin seven screens and dialogs responsive at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const errors: string[] = []
    page.on('pageerror', e => errors.push(e.message))
    for (const route of ['', 'accounts', 'vehicles', 'drivers', 'history', 'settings', 'audit']) {
      await page.goto(`/admin/${route}`)
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (['accounts', 'vehicles', 'drivers', 'settings'].includes(route)) {
        await page.getByRole('button', { name: route === 'settings' ? 'แก้ไขการตั้งค่า' : route === 'accounts' ? '+ เพิ่มบัญชี' : route === 'vehicles' ? '+ เพิ่มรถ' : '+ เพิ่มคนขับ', exact: true }).click()
        const dialog = page.getByRole('dialog')
        await expect(dialog).toBeVisible()
        expect(await dialog.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && el.scrollWidth <= el.clientWidth })).toBe(true)
        await dialog.getByRole('button', { name: 'ยกเลิก', exact: true }).click()
        await expect(dialog).toHaveCount(0)
        if (route !== 'settings') {
          await page.getByRole('row').filter({ has: page.getByRole('button', { name: route === 'accounts' ? 'จัดการบัญชี' : route === 'vehicles' ? 'จัดการรถ' : 'จัดการคนขับ', exact: true }) }).first().getByRole('button').click()
          await page.getByRole('button', { name: route === 'vehicles' ? 'ปิดใช้งานรถ' : 'ระงับการใช้งาน', exact: true }).click()
          await expect(page.getByLabel('เหตุผลในการระงับ / ปิดใช้งาน')).toBeVisible()
          expect(await dialog.evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && el.scrollWidth <= el.clientWidth })).toBe(true)
          await dialog.screenshot({ path: `test-results/admin-${route}-confirm-${width}.png` })
          await page.keyboard.press('Escape')
          await expect(dialog).toHaveCount(0)
        }
      }
      await page.screenshot({ path: `test-results/admin-${route || 'dashboard'}-${width}.png`, fullPage: true })
    }
    if (width < 768) {
      await page.getByRole('button', { name: 'เมนูผู้ดูแลระบบ', exact: true }).click()
      await page.getByRole('link', { name: 'ภาพรวม', exact: true }).click()
      await expect(page.getByRole('heading', { name: 'ภาพรวมระบบ' })).toBeVisible()
      await expect(page.getByRole('button', { name: 'เมนูผู้ดูแลระบบ', exact: true })).toHaveAttribute('aria-expanded', 'false')
    }
    expect(errors).toEqual([])
  })
}
