const key = 'ban-klang-transit:demo:v1'
const save = (page: Page) => page.getByRole('button', { name: 'บันทึก', exact: true }).click()
async function saved(page: Page) { await expect(page.getByRole('dialog')).toHaveCount(0); await expect(page.getByRole('status')).toContainText('บันทึกข้อมูล') }
async function addAccount(page: Page, name = 'คนขับ ใหม่จำลอง', username = 'new.driver.demo') {
  await page.goto('/admin/accounts')
  await page.getByRole('button', { name: '+ เพิ่มบัญชี', exact: true }).click()
  await page.getByLabel('ชื่อ–นามสกุล', { exact: true }).fill(name)
  await page.getByLabel('ชื่อผู้ใช้งาน', { exact: true }).fill(username)
  await page.getByLabel('บทบาทและสิทธิ์').selectOption('Driver')
  await save(page); await saved(page)
}
async function fixture(page: Page) {
  await page.clock.setFixedTime(new Date('2026-10-26T03:30:00Z'))
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'ภาพรวมระบบ' })).toBeVisible()
  await page.evaluate(storageKey => {
    const state = JSON.parse(localStorage.getItem(storageKey)!)
    const details = { bookingFor: 'self', acknowledged: true, patientName: 'ผู้รับบริการจำลอง', contactName: '', phone: '0800000000', relationship: '', hospital: 'โรงพยาบาลจำลอง', date: '2026-10-30', time: '13:10', assistance: 'walk', extras: [], pickup: { label: 'จุดรับจำลอง', x: 50, y: 50 } }
    const base = { patientName: details.patientName, appointmentAt: '2026-10-30T06:10:00.000Z', createdAt: '2026-10-26T03:30:00.000Z', status: 'approved', details }
    state.bookings = [{ ...base, id: 'BK-ADMIN-1' }, { ...base, id: 'BK-ADMIN-2' }]
    localStorage.setItem(storageKey, JSON.stringify(state))
  }, key)
  await page.reload()
}
async function assign(page: Page) {
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  await expect(page).toHaveURL(/tracking$/)
}

