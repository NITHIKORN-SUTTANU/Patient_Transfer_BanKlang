import { test, expect } from '@playwright/test'
import { startAdminTestApi, syntheticPassword } from './helpers/admin-postgres.mjs'

test.use({ actionTimeout: 10000 })

test('original admin screens manage resources, windows and driver revocation through real API/PostgreSQL', async ({ page }) => {
  test.setTimeout(90000)
  const adminUrl = process.env.DATABASE_TEST_ADMIN_URL
  test.skip(!adminUrl, 'Run npm run test:admin:integration with a local test database configured')
  const api = await startAdminTestApi(adminUrl!)
  const depot = '20000000-0000-4000-8000-000000000001'
  try {
    // Routing only: all API payloads/statuses come from the real ephemeral server.
    await page.route('**/api/**', async route => {
      const path = new URL(route.request().url()).pathname
      try { await route.fulfill({ response: await route.fetch({ url: `${api.base}${path}` }) }) }
      catch { throw new Error(`Ephemeral admin API request failed: ${path}`) }
    })
    await page.goto('/staff/login?next=%2Fadmin%2Fvehicles')
    await page.getByLabel('ชื่อผู้ใช้', { exact: true }).fill('synthetic-admin')
    await page.getByLabel('รหัสผ่าน', { exact: true }).fill(syntheticPassword)
    await page.getByRole('button', { name: 'เข้าสู่ระบบ', exact: true }).click()
    await page.getByRole('link', { name: 'เปิดหน้าผู้ดูแลระบบ', exact: true }).click()
    await page.getByRole('button', { name: '+ เพิ่มรถ', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('ชื่อรถ', { exact: true }).fill('รถทดสอบจริง')
    await dialog.getByLabel('ทะเบียนรถ', { exact: true }).fill('REAL-TEST-01')
    await dialog.getByLabel('ประเภทรถ', { exact: true }).fill('รถรับส่งทั่วไป')
    await dialog.getByRole('combobox', { name: 'ตำแหน่งเริ่มต้นที่ตรวจสอบแล้ว', exact: true }).selectOption(depot)
    await dialog.getByLabel('พร้อมตั้งแต่ (เวลาไทย)', { exact: true }).fill('2030-01-12T08:00')
    await dialog.getByRole('checkbox', { name: 'ตรวจสอบตำแหน่งและความพร้อมเริ่มต้นจริงแล้ว', exact: true }).check()
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('เพิ่มรถสังเคราะห์สำหรับทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const vehicleRow = page.getByRole('row').filter({ hasText: 'REAL-TEST-01' })
    await expect(vehicleRow).toBeVisible()
    const vehicle = (await api.pool.query("SELECT * FROM patient_transfer.vehicles WHERE plate='REAL-TEST-01'")).rows[0]
    expect(vehicle.location_id).toBe(depot)
    expect((await api.pool.query('SELECT count(*)::int AS count FROM patient_transfer.availability_windows WHERE vehicle_id=$1', [vehicle.id])).rows[0].count).toBe(0)
    await vehicleRow.getByRole('button', { name: 'ช่วงเวลารถ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('เริ่มช่วงเวลา (เวลาไทย)', { exact: true }).fill('2030-01-15T06:00')
    await dialog.getByLabel('สิ้นสุดช่วงเวลา (เวลาไทย)', { exact: true }).fill('2030-01-15T16:00')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('กำหนดช่วงเวลาทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึกช่วงเวลา', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const window = (await api.pool.query('SELECT * FROM patient_transfer.availability_windows WHERE vehicle_id=$1', [vehicle.id])).rows[0]
    expect(window.starts_at.toISOString()).toBe('2030-01-14T23:00:00.000Z')
    await vehicleRow.getByRole('button', { name: 'ช่วงเวลารถ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'ช่วงเวลาที่บันทึกไว้', exact: true }).selectOption(window.id)
    await dialog.getByLabel('สิ้นสุดช่วงเวลา (เวลาไทย)', { exact: true }).fill('2030-01-15T15:00')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('ปรับช่วงเวลาทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึกช่วงเวลา', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await vehicleRow.getByRole('button', { name: 'ช่วงเวลารถ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'ช่วงเวลาที่บันทึกไว้', exact: true }).selectOption(window.id)
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('ปิดช่วงเวลาทดสอบ')
    await dialog.getByRole('button', { name: 'ปิดช่วงเวลานี้', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    expect((await api.pool.query('SELECT retired_at FROM patient_transfer.availability_windows WHERE id=$1', [window.id])).rows[0].retired_at).not.toBeNull()
    await api.pool.query("INSERT INTO patient_transfer.resource_holds(vehicle_id,starts_at,reason,created_by) VALUES($1,'2030-01-12T00:00:00Z','Synthetic hold','00000000-0000-4000-8000-000000000004')", [vehicle.id])
    await vehicleRow.getByRole('button', { name: 'จัดการรถ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('ชื่อรถ', { exact: true }).fill('รถเดิมเปลี่ยนชื่อทดสอบ')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('ปรับชื่อโดยคงสถานะรอยืนยัน')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    expect((await api.pool.query('SELECT count(*)::int AS count FROM patient_transfer.resource_holds WHERE vehicle_id=$1 AND ends_at IS NULL', [vehicle.id])).rows[0].count).toBe(1)

    await page.getByRole('link', { name: 'ผู้ใช้งานและสิทธิ์', exact: true }).click()
    await page.getByRole('button', { name: '+ เพิ่มบัญชี', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('ชื่อ–นามสกุล', { exact: true }).fill('คนขับสังเคราะห์ใหม่')
    await dialog.getByLabel('ชื่อผู้ใช้งาน', { exact: true }).fill('real-test-driver')
    await dialog.getByRole('combobox', { name: 'บทบาทและสิทธิ์', exact: true }).selectOption('Driver')
    await dialog.getByLabel('รหัสผ่านเริ่มต้น', { exact: true }).fill(syntheticPassword)
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('บัญชีทดสอบคนขับ')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const account = (await api.pool.query("SELECT id FROM patient_transfer.users WHERE username='real-test-driver'")).rows[0]
    await page.getByRole('link', { name: 'คนขับ', exact: true }).click()
    await page.getByRole('button', { name: '+ เพิ่มคนขับ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'บัญชีผู้ใช้งาน Role: Driver', exact: true }).selectOption(account.id)
    await dialog.getByLabel('เบอร์ติดต่อ', { exact: true }).fill('0800000000')
    await dialog.getByRole('combobox', { name: 'ตำแหน่งเริ่มต้นที่ตรวจสอบแล้ว', exact: true }).selectOption(depot)
    await dialog.getByLabel('พร้อมตั้งแต่ (เวลาไทย)', { exact: true }).fill('2030-01-12T08:00')
    await dialog.getByRole('checkbox', { name: 'ตรวจสอบตำแหน่งและความพร้อมเริ่มต้นจริงแล้ว', exact: true }).check()
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('เพิ่มคนขับทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const login = await fetch(`${api.base}/api/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'real-test-driver', password: syntheticPassword }) })
    const session = await login.json()
    expect(login.status).toBe(200)
    const driverRow = page.getByRole('row').filter({ hasText: 'คนขับสังเคราะห์ใหม่' })
    await driverRow.getByRole('button', { name: 'จัดการคนขับ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'สถานะคนขับ', exact: true }).selectOption('false')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('ปิดคนขับทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(driverRow.getByText('ไม่พร้อมใช้งาน', { exact: true })).toBeVisible()
    expect((await fetch(`${api.base}/api/auth/me`, { headers: { Authorization: `Bearer ${session.token}` } })).status).toBe(401)
    await page.getByRole('link', { name: 'การตั้งค่าระบบ', exact: true }).click()
    await page.getByRole('button', { name: '+ เพิ่มโรงพยาบาล', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('ชื่อ', { exact: true }).fill('โรงพยาบาลทดสอบจริง')
    await dialog.getByLabel('ละติจูด', { exact: true }).fill('18.61')
    await dialog.getByLabel('ลองจิจูด', { exact: true }).fill('99.06')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('ข้อมูลสังเคราะห์สำหรับทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('row').filter({ hasText: 'โรงพยาบาลทดสอบจริง' })).toBeVisible()
    expect((await api.pool.query("SELECT count(*)::int AS n FROM patient_transfer.hospitals WHERE name='โรงพยาบาลทดสอบจริง'")).rows[0].n).toBe(1)
    await page.getByRole('button', { name: '+ เพิ่มวันปิดบริการ', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('วันที่ปิดบริการ', { exact: true }).fill('2030-01-26')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('ปิดบริการทดสอบ')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const closureRow=page.getByRole('row').filter({ hasText: '2030-01-26' })
    await closureRow.getByRole('button', { name: 'จัดการวันปิดบริการ', exact: true }).click()
    dialog=page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'สถานะ', exact: true }).selectOption('false')
    await dialog.getByLabel('เหตุผลในการเปลี่ยนแปลง', { exact: true }).fill('เปิดบริการอีกครั้ง')
    await dialog.getByRole('button', { name: 'บันทึก', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(closureRow.getByText('เปิดบริการอีกครั้ง', { exact: true }).first()).toBeVisible()
    expect((await api.pool.query("SELECT active FROM patient_transfer.service_closures WHERE closed_on='2030-01-26'")).rows[0].active).toBe(false)
  } finally {
    if (!page.isClosed()) {
      await page.unrouteAll({ behavior: 'ignoreErrors' })
      await page.close()
    }
    await api.close()
  }
})
