test('time columns scroll independently, support keyboard selection, and confirm the selected time', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await enterBooking(page)
  const trigger = page.getByRole('button', { name: /เวลานัดหมาย \*/ })
  await trigger.click()
  const hours = page.getByRole('listbox', { name: 'ชั่วโมง', exact: true })
  const minutes = page.getByRole('listbox', { name: 'นาที', exact: true })
  await expect(hours.getByRole('option', { name: '10', exact: true })).toHaveAttribute('aria-selected', 'true')
  await hours.hover()
  await page.mouse.wheel(0, 144)
  await expect(hours.getByRole('option', { name: '11', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(minutes.getByRole('option', { name: '30', exact: true })).toHaveAttribute('aria-selected', 'true')
  await minutes.hover()
  await page.mouse.wheel(0, -96)
  await expect(minutes.getByRole('option', { name: '29', exact: true })).toHaveAttribute('aria-selected', 'true')
  await hours.evaluate(async element => {
    for (let n = 0; n < 3; n++) element.dispatchEvent(new WheelEvent('wheel', { deltaY: 96, bubbles: true, cancelable: true }))
  })
  await expect(hours.getByRole('option', { name: '14', exact: true })).toHaveAttribute('aria-selected', 'true')
  await hours.hover()
  await page.mouse.wheel(0, 96)
  await expect(hours.getByRole('option', { name: '15', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.addStyleTag({ content: '.booking-time-option { font-size:40px; } .booking-time-option[aria-selected=true] { font-size:56px; }' })
  await expect.poll(() => hours.getByRole('option', { name: '15', exact: true }).evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThan(48)
  await setPickerTime(page, 'ชั่วโมง', '17')
  await setPickerTime(page, 'นาที', '42')
  await hours.focus()
  await page.keyboard.press('Home')
  await expect(hours.getByRole('option', { name: '00', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('End')
  await minutes.focus()
  await page.keyboard.press('End')
  await expect(page.getByText('23:59 น.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'ยืนยันเวลา', exact: true })).toBeInViewport()
  await page.getByRole('button', { name: 'ยืนยันเวลา', exact: true }).click()
  await expect(trigger).toContainText('23:59')
})

test.describe('touch time picker', () => {
  test.use({ hasTouch: true })
  test('swiping the minute column scrolls it without moving the hour column', async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 640 })
    await enterBooking(page)
    await page.getByRole('button', { name: /เวลานัดหมาย \*/ }).click()
    const minutes = page.getByRole('listbox', { name: 'นาที', exact: true })
    const hours = page.getByRole('listbox', { name: 'ชั่วโมง', exact: true })
    const initial = await minutes.evaluate(element => element.scrollTop)
    const bounds = (await minutes.boundingBox())!
    const session = await page.context().newCDPSession(page)
    const x = bounds.x + bounds.width / 2
    const y = bounds.y + bounds.height * .75
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    for (let step = 1; step <= 6; step++) {
      await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - step * 16 }] })
      await page.evaluate(() => new Promise(requestAnimationFrame))
    }
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => minutes.evaluate(element => element.scrollTop)).toBeGreaterThan(initial)
    await expect(hours.getByRole('option', { name: '10', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('button', { name: 'ยืนยันเวลา', exact: true })).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
    await session.detach()
  })
})

