import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

const roles = [
  { route: '/dispatcher', label: 'เมนูเจ้าหน้าที่จัดรถ', link: 'ติดตามงานรับส่ง', destination: '/dispatcher/tracking' },
  { route: '/driver', label: 'เมนูคนขับ', link: 'ประวัติ', destination: '/driver/history' },
  { route: '/admin', label: 'เมนูผู้ดูแลระบบ', link: 'การตั้งค่าระบบ', destination: '/admin/settings' },
]

test('admin sidebar keeps logo, navigation and bottom toggle in its collapsed rail', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/admin')
  const sidebar = page.locator('#admin-sidebar')
  await sidebar.getByRole('button', { name: 'ย่อเมนูด้านข้าง', exact: true }).click()
  expect((await sidebar.boundingBox())!.width).toBe(80)
  expect((await page.locator('main').boundingBox())!.x).toBe(80)
  await expect(sidebar.getByRole('img', { name: 'ตราเทศบาลจำลอง' })).toBeVisible()
  const toggle = sidebar.getByRole('button', { name: 'ขยายเมนูด้านข้าง', exact: true })
  expect((await toggle.boundingBox())!.y).toBeGreaterThan(800)
  expect(await toggle.evaluate(element => getComputedStyle(element).borderTopWidth)).toBe('0px')
  await sidebar.getByRole('link', { name: 'ผู้ใช้งานและสิทธิ์', exact: true }).click()
  await expect(page).toHaveURL(/admin\/accounts$/)
  expect((await sidebar.boundingBox())!.width).toBe(80)
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(axe.violations).toEqual([])
  await page.screenshot({ path: 'test-results/admin-icon-rail.png' })
  await toggle.focus()
  await page.keyboard.press('Enter')
  expect((await sidebar.boundingBox())!.width).toBe(250)
  const cars = sidebar.getByRole('link', { name: 'รถรับส่ง', exact: true })
  await cars.click()
  await expect(page).toHaveURL(/admin\/vehicles$/)
  await expect(cars).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('button', { name: '+ เพิ่มรถ', exact: true })).toBeVisible()
  await expect(page.locator('[aria-label="ประเภทรัพยากร"]')).toHaveCount(0)
  await sidebar.getByRole('link', { name: 'คนขับ', exact: true }).click()
  await expect(page).toHaveURL(/admin\/drivers$/)
  const current = sidebar.getByRole('link', { name: 'คนขับ', exact: true })
  await expect(cars).not.toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('button', { name: '+ เพิ่มคนขับ', exact: true })).toBeVisible()
  await expect(current).toHaveAttribute('aria-current', 'page')
  await current.hover()
  expect(await current.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(215, 243, 236)')
  await page.keyboard.press('Tab')
  await current.focus()
  expect(await current.evaluate(element => getComputedStyle(element).outlineStyle)).toBe('solid')
})

test('dispatcher desktop sidebar collapses to an accessible icon rail without affecting mobile navigation', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/dispatcher')
  const sidebar = page.locator('#dispatcher-sidebar')
  const main = page.locator('#dispatcher-main')
  const initial = (await main.boundingBox())!
  await page.getByRole('button', { name: 'ย่อเมนูด้านข้าง', exact: true }).click()
  await expect(sidebar).toBeVisible()
  expect((await sidebar.boundingBox())!.width).toBe(80)
  await expect(sidebar.getByRole('img', { name: 'ตราเทศบาลจำลอง' })).toBeVisible()
  await expect(sidebar.getByRole('link', { name: 'แดชบอร์ดงานรับส่ง', exact: true })).toBeVisible()
  const expanded = (await main.boundingBox())!
  expect(expanded.x).toBe(80)
  expect(expanded.width).toBeGreaterThan(initial.width)
  const show = page.getByRole('button', { name: 'ขยายเมนูด้านข้าง', exact: true })
  await expect(show).toHaveAttribute('aria-expanded', 'false')
  const arrowBounds = (await show.boundingBox())!
  expect(arrowBounds.y + arrowBounds.height).toBeGreaterThan(800)
  expect(await show.evaluate(element => getComputedStyle(element).borderTopWidth)).toBe('0px')
  await expect(sidebar.getByRole('button', { name: 'ขยายเมนูด้านข้าง', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/dispatcher-icon-rail.png' })
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(axe.violations).toEqual([])
  await sidebar.getByRole('link', { name: 'ติดตามงานรับส่ง', exact: true }).click()
  await expect(page).toHaveURL(/dispatcher\/tracking$/)
  expect((await sidebar.boundingBox())!.width).toBe(80)
  await page.setViewportSize({ width: 320, height: 640 })
  await expect(sidebar).toBeVisible()
  await page.getByRole('button', { name: 'เมนูเจ้าหน้าที่จัดรถ', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'เมนูเจ้าหน้าที่จัดรถ', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1280, height: 900 })
  await show.focus()
  await page.keyboard.press('Enter')
  await expect(sidebar).toBeVisible()
  await expect(page.getByRole('button', { name: 'ย่อเมนูด้านข้าง', exact: true })).toHaveAttribute('aria-expanded', 'true')
})

for (const role of roles) {
  test(`${role.route} navigation collapses, supports keyboard, and adapts to resizing`, async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.setViewportSize({ width: 320, height: 640 })
    await page.goto(role.route)
    const toggle = page.getByRole('button', { name: role.label, exact: true })
    const navigation = page.getByRole('navigation', { name: role.label, exact: true })
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(navigation).toBeHidden()
    const header = page.locator(role.route === '/admin' ? '.admin-brand' : '.workspace-nav-heading')
    const headerBounds = (await header.boundingBox())!
    const toggleBounds = (await toggle.boundingBox())!
    expect(toggleBounds.x).toBeGreaterThanOrEqual(headerBounds.x + headerBounds.width)
    expect(toggleBounds.y).toBeLessThan(headerBounds.y + headerBounds.height)
    const shortcut = page.getByRole('link', { name: 'กลับเลือกบทบาท', exact: true })
    const shortcutBounds = (await shortcut.boundingBox())!
    expect(shortcutBounds.x).toBe(12)
    expect(shortcutBounds.y + shortcutBounds.height).toBe(628)
    await toggle.click()
    await expect(navigation).toBeVisible()
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    const drawer = page.getByRole('dialog', { name: role.label, exact: true })
    const drawerBounds = (await drawer.boundingBox())!
    expect(drawerBounds.width).toBeLessThanOrEqual(320 * 0.6)
    expect(drawerBounds.x).toBeGreaterThan(0)
    expect(drawerBounds.x + drawerBounds.width).toBe(320)
    expect(drawerBounds.height).toBe(640)
    await expect(page.getByRole('button', { name: 'ปิดเมนู', exact: true })).toBeFocused()
    await navigation.getByRole('link').last().focus()
    await page.keyboard.press('Tab')
    await expect(page.getByRole('button', { name: 'ปิดเมนู', exact: true })).toBeFocused()
    await page.mouse.click(8, 320)
    await expect(drawer).toBeHidden()
    await expect(toggle).toBeFocused()
    await toggle.click()
    await page.screenshot({ path: `test-results/navigation-${role.route.slice(1)}-320.png` })
    await navigation.getByRole('link').first().focus()
    await page.keyboard.press('Escape')
    await expect(navigation).toBeHidden()
    await expect(toggle).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(navigation).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
    expect(axe.violations).toEqual([])
    await navigation.getByRole('link', { name: role.link, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`${role.destination}$`))
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(navigation).toBeHidden()
    await page.setViewportSize({ width: 768, height: 900 })
    await expect(toggle).toBeHidden()
    await expect(navigation).toBeVisible()
    await page.setViewportSize({ width: 375, height: 640 })
    await expect(toggle).toBeVisible()
    await expect(navigation).toBeHidden()
  })

  test(`${role.route} desktop navigation stays on the left`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto(role.route)
    const navigation = page.getByRole('navigation', { name: role.label, exact: true })
    const links = await navigation.getByRole('link').all()
    const first = (await links[0].boundingBox())!
    const last = (await links[links.length - 1].boundingBox())!
    expect(last.x).toBe(first.x)
    expect(last.y).toBeGreaterThan(first.y)
    const main = (await page.locator('main').boundingBox())!
    expect(main.x).toBeGreaterThanOrEqual(first.x + first.width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
